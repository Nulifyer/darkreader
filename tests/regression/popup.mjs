import assert from 'node:assert/strict';
import {cp, mkdir, mkdtemp, readFile, rm, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {launch} from 'puppeteer-core';

assert.ok(process.env.CHROME_BIN, 'Set CHROME_BIN and build the release first.');
const output = path.resolve('build/audit/popup-redesign');
await mkdir(output, {recursive: true});
const profile = await mkdtemp('/tmp/darkreader-popup-');
const extension = path.join(profile, 'extension');
await cp(path.resolve('build/release/chrome-mv3'), extension, {recursive: true});
const fixture = '<!doctype html><html><head><style>body{background:white;color:black;min-height:100vh}h1{color:black}</style></head><body><h1>Popup regression</h1><p>Website content stays separate from popup settings.</p></body></html>';
const results = [];
let browser;
try {
    browser = await launch({executablePath: process.env.CHROME_BIN, headless: false, pipe: true, enableExtensions: true, userDataDir: profile});
    const id = await browser.installExtension(extension);
    const page = await browser.newPage();
    await page.setRequestInterception(true);
    let html = fixture;
    page.on('request', (request) => request.isNavigationRequest() ? request.respond({status: 200, contentType: 'text/html', body: html}) : request.abort());
    await page.goto('https://popup-test.example/article');
    const background = await browser.waitForTarget((target) => target.type() === 'service_worker' && target.url().startsWith(`chrome-extension://${id}/`));
    const worker = await background.worker();
    await worker.evaluate((url) => chrome.windows.create({url, type: 'popup', width: 460, height: 640}), `chrome-extension://${id}/ui/popup/index.html`);
    const popupTarget = await browser.waitForTarget((target) => target.type() === 'page' && target.url() === `chrome-extension://${id}/ui/popup/index.html`);
    const popup = await popupTarget.page();
    const errors = [];
    popup.on('pageerror', (error) => errors.push(String(error)));
    await popup.setViewport({width: 440, height: 592, deviceScaleFactor: 1});

    await popup.waitForSelector('.filter-settings');
    const collect = () => popup.evaluate(async () => (await chrome.runtime.sendMessage({type: 'ui-bg-get-data'})).data);
    const change = (data) => popup.evaluate((data) => {chrome.runtime.sendMessage({type: 'ui-bg-change-settings', data});}, data);
    const original = (await collect()).settings;
    await change({enabled: true, enabledByDefault: true, enabledFor: [], disabledFor: [], syncSettings: false, syncSitesFixes: false, customThemes: [], presets: [], detectDarkTheme: false, automation: {enabled: false, mode: '', behavior: 'OnOff'}, theme: {...original.theme, brightness: 100, contrast: 100, preserveImages: true}});
    await popup.bringToFront();
    const wait = (predicate) => popup.waitForFunction(predicate, {polling: 100, timeout: 10000});
    const view = async (id) => {await popup.click(`#tab-${id}`); await wait(() => document.querySelector('[role="tab"][aria-selected="true"]') != null);};
    const range = async (label, value) => {
        await popup.$eval(`input[aria-label="${label}"]`, (node, value) => {node.value = String(value); node.dispatchEvent(new Event('input', {bubbles: true}));}, value);
        assert.equal(await popup.$eval(`input[aria-label="${label}"]`, (node) => node.closest('.appearance-adjustment').querySelector('button').textContent), `${value}%`, 'range feedback updates while dragging');
        await popup.$eval(`input[aria-label="${label}"]`, (node) => node.dispatchEvent(new Event('change', {bubbles: true})));
    };
    const capture = async (name) => {
        await popup.bringToFront();
        await popup.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
        const layout = await popup.evaluate(() => {
            const content = document.querySelector('.popup-content').getBoundingClientRect();
            const footer = document.querySelector('.popup-footer').getBoundingClientRect();
            const body = document.body.getBoundingClientRect();
            return {width: body.width, height: body.height, horizontalOverflow: document.documentElement.scrollWidth > innerWidth, footerOverlaps: content.bottom > footer.top + 1, panelScrollHeight: document.querySelector('.popup-content').scrollHeight, panelHeight: content.height};
        });
        assert.equal(layout.horizontalOverflow, false, name);
        assert.equal(layout.footerOverlaps, false, name);
        assert.ok(layout.height <= 600, 'fits Chromium popup height');
        await popup.screenshot({path: path.join(output, `${name}.png`)});
        results.push({name, layout});
    };
    await wait(() => document.querySelector('.appearance-scope').textContent.includes('Using your defaults'));

    await capture('site');
    await range('Brightness', 85);
    await wait(async () => (await chrome.runtime.sendMessage({type: 'ui-bg-get-data'})).data.settings.customThemes[0]?.theme.brightness === 85);
    assert.equal((await collect()).settings.theme.brightness, 100, 'site edit cannot change global brightness');
    await popup.click('.appearance-scope button');
    await wait(() => document.querySelector('input[aria-label="Brightness"]').value === '100');
    await view('defaults'); await range('Brightness', 110);
    await wait(async () => (await chrome.runtime.sendMessage({type: 'ui-bg-get-data'})).data.settings.theme.brightness === 110);
    await view('site');
    assert.equal(await popup.$eval('input[aria-label="Brightness"]', (node) => node.value), '110');
    await view('defaults'); await popup.click('button[aria-label="Reset brightness"]');
    await popup.click('.image-settings__global input');
    await wait(async () => !(await chrome.runtime.sendMessage({type: 'ui-bg-get-data'})).data.settings.theme.preserveImages);
    await view('site'); await popup.select('.image-settings__select', 'preserve');
    await wait(async () => (await chrome.runtime.sendMessage({type: 'ui-bg-get-data'})).data.settings.imagePreservationOverrides[0]?.preserveImages === true);
    await view('defaults'); await capture('defaults');
    await popup.click('.image-settings__global input');
    await view('site'); await popup.select('.image-settings__select', 'global');
    await wait(async () => (await chrome.runtime.sendMessage({type: 'ui-bg-get-data'})).data.settings.imagePreservationOverrides.length === 0);
    // A shared URL rule must not make a local edit affect its sibling sites.
    const shared = {url: ['popup-test.example', 'sibling.example'], theme: {...original.theme, brightness: 95}};
    await change({customThemes: [shared]});
    await wait(() => document.querySelector('input[aria-label="Brightness"]').value === '95');
    await range('Brightness', 88);
    await wait(async () => (await chrome.runtime.sendMessage({type: 'ui-bg-get-data'})).data.settings.customThemes[0]?.theme.brightness === 88);
    const local = (await collect()).settings;
    assert.deepEqual(local.customThemes[0].url, ['popup-test.example']);
    assert.equal(local.customThemes[1].theme.brightness, 95);
    await popup.click('.appearance-scope button');
    await wait(() => document.querySelector('input[aria-label="Brightness"]').value === '95');
    assert.deepEqual((await collect()).settings.customThemes, [shared]);
    await change({customThemes: [], presets: [{id: 'reading', name: 'Reading', urls: ['popup-test.example'], theme: {...original.theme, brightness: 92}}]});
    await wait(() => document.querySelector('input[aria-label="Brightness"]').value === '92');
    await range('Brightness', 87);
    await wait(async () => (await chrome.runtime.sendMessage({type: 'ui-bg-get-data'})).data.settings.customThemes[0]?.theme.brightness === 87);
    assert.equal((await collect()).settings.presets[0].theme.brightness, 92);
    await popup.click('.appearance-scope button');
    await wait(() => document.querySelector('input[aria-label="Brightness"]').value === '92');
    await change({customThemes: [], presets: []});
    await popup.click('.header__power');
    await wait(() => document.querySelector('.header__power').getAttribute('aria-pressed') === 'false');
    await capture('paused');
    await view('defaults'); await range('Contrast', 105);
    await wait(async () => (await chrome.runtime.sendMessage({type: 'ui-bg-get-data'})).data.settings.theme.contrast === 105);
    await popup.click('.header__power');
    await view('site'); await view('settings');
    await capture('settings');
    await popup.click('.automation-system input');
    await wait(async () => (await chrome.runtime.sendMessage({type: 'ui-bg-get-data'})).data.settings.automation.mode === 'system');
    await popup.click('.automation-system input');
    await popup.evaluate(() => Array.from(document.querySelectorAll('summary')).find((node) => node.textContent === 'Schedule').click());
    await popup.select('.automation-mode', 'time');
    await popup.waitForSelector('input[aria-label="Start time"]');
    await popup.$eval('input[aria-label="Start time"]', (node) => {node.value = '21:30'; node.dispatchEvent(new Event('change', {bubbles: true}));});
    await wait(async () => (await chrome.runtime.sendMessage({type: 'ui-bg-get-data'})).data.settings.time.activation === '21:30');
    await popup.select('.automation-mode', 'location');
    await popup.waitForSelector('input[aria-label="latitude"]');
    await popup.$eval('input[aria-label="latitude"]', (node) => {node.value = '40.7'; node.dispatchEvent(new Event('change', {bubbles: true}));});
    await wait(async () => (await chrome.runtime.sendMessage({type: 'ui-bg-get-data'})).data.settings.location.latitude === 40.7);
    await popup.select('.automation-mode', '');
    await popup.evaluate(() => Array.from(document.querySelectorAll('summary')).find((node) => node.textContent === 'Rendering').click());
    await popup.select('select[aria-label="Rendering engine"]', 'cssFilter');
    await wait(async () => (await chrome.runtime.sendMessage({type: 'ui-bg-get-data'})).data.settings.customThemes[0]?.theme.engine === 'cssFilter');
    await page.bringToFront(); await page.waitForFunction(() => document.documentElement.dataset.darkreaderMode === 'dynamic');
    await popup.bringToFront(); await view('site');
    await popup.focus('#tab-site'); await popup.keyboard.press('ArrowRight');
    await wait(() => document.activeElement.id === 'tab-defaults' && document.activeElement.getAttribute('aria-selected') === 'true');
    await popup.keyboard.press('End');
    await wait(() => document.activeElement.id === 'tab-settings');
    await popup.keyboard.press('Home');
    await wait(() => document.activeElement.id === 'tab-site');
    await popup.evaluate(() => document.querySelector('.appearance-details summary').click());
    await capture('fine-tuning');
    await view('defaults'); await view('site');
    await popup.evaluate(() => document.documentElement.classList.add('mobile'));
    await popup.setViewport({width: 320, height: 592}); await capture('narrow');
    await popup.evaluate(() => document.documentElement.classList.remove('mobile'));
    await popup.setViewport({width: 440, height: 592});
    await change({enabled: true, customThemes: [], presets: [], detectDarkTheme: true, automation: {...original.automation, enabled: false}});
    html = fixture.replace('<html>', '<html class="dark">').replace('background:white;color:black', 'background:#16191c;color:#e5e7eb');
    await page.goto('https://popup-native.example/'); await page.bringToFront();
    await new Promise((resolve) => setTimeout(resolve, 1000));
    await popup.reload(); await popup.waitForSelector('.filter-settings'); await popup.bringToFront();
    await wait(() => document.querySelector('.header__status').textContent.includes('website’s dark theme'));
    await capture('native-theme');
    await popup.click('.header__site input');
    await wait(async () => (await chrome.runtime.sendMessage({type: 'ui-bg-get-data'})).data.settings.enabledFor.includes('popup-native.example'));
    await page.bringToFront(); await page.waitForFunction(() => document.documentElement.dataset.darkreaderMode === 'dynamic');
    html = fixture;
    await page.goto('https://a-long-website-name-for-checking-the-popup.another-long-subdomain.example/');
    await page.bringToFront(); await popup.reload(); await popup.waitForSelector('.filter-settings'); await popup.bringToFront();
    await wait(() => document.querySelector('.header__site strong').textContent.includes('a-long-website'));
    await capture('long-hostname');
    await change({customThemes: original.customThemes, theme: {...original.theme, preserveImages: true}});
    await page.goto('https://docs.google.com/document/d/popup-preview/edit');
    await page.bringToFront(); await popup.reload(); await popup.waitForSelector('.filter-settings'); await popup.bringToFront();
    await wait(() => document.querySelector('.header__site strong').textContent === 'docs.google.com');
    await capture('docs');
    await page.goto('chrome://extensions'); await page.bringToFront(); await popup.reload(); await popup.waitForSelector('.filter-settings'); await popup.bringToFront();
    await wait(() => document.querySelector('.header__status').textContent.includes('Unavailable'));
    assert.equal(await popup.$eval('.appearance-fields', (node) => node.disabled), true);
    await capture('protected');
    await view('defaults');
    assert.equal(await popup.$eval('.appearance-fields', (node) => node.disabled), false);
    assert.deepEqual(errors, []);
    const hashes = Object.fromEntries(await Promise.all(['ui/popup/index.js', 'ui/popup/style.css', 'inject/index.js'].map(async (name) => [name, createHash('sha256').update(await readFile(path.join(extension, name))).digest('hex')])));
    await writeFile(path.join(output, 'results.json'), JSON.stringify({hashes, checks: 'PASS: site/default isolation, shared rules, presets, reset/inheritance, independent image rules, paused editing, schedule/system controls, rendering preservation, keyboard tabs, native override, protected page, narrow and long-host layouts', results}, null, 2));
    console.log('PASS: popup interactions, settings scopes, inheritance, native/protected/paused states, keyboard navigation, and 440 px desktop and 320 px mobile-fallback layouts.');
} finally {
    await browser?.close();
    await rm(profile, {recursive: true, force: true});
}
